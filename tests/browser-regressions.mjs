for (const stage of ['before-refresh', 'during-refresh']) {
  test(`switching account ${stage} cannot replay or restore A`, async () => {
    const a = 'race-a-' + stage, b = 'race-b-' + stage;
    const records = {[a]: record('Alice race'), [b]: record('Bruno race', 1, 'apple')};
    const heldSave = deferred(), heldRefresh = deferred(), finishSave = deferred(), finishRefresh = deferred();
    let intercepted = false, refreshRequests = 0;
    await withHarness(records, async harness => {
      const {page, context} = harness;
      await seed(page, a, records[a]); await waitDiary(page);
      const other = await context.newPage();
      await other.goto(baseURL, {waitUntil: 'networkidle'}); await waitDiary(other);
      await addWater(page, 350);
      await heldSave.promise;
      if (stage === 'during-refresh') {finishSave.resolve(); await heldRefresh.promise}
      await switchAccount(other, b, records[b]);
      await Promise.all([activeAccount(page, 'Bruno race'), activeAccount(other, 'Bruno race')]);
      finishSave.resolve(); finishRefresh.resolve();
      // A subsequent B write also proves the cancelled A operation did not
      // leave B's sync queue stuck or incorrectly alter its revision.
      await addWater(page, 500); await savedRecord(page, b);
      assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('kalora-session')).user.id), b);
      assert.equal(harness.cloud[b].state.profile.name, 'Bruno race');
      assert.deepEqual(harness.cloud[b].state.waterEntries.map(entry => entry.amountMl), [500]);
      assertNoCrossAccountSave(harness, b, 'Bruno race');
      assert.equal(refreshRequests, stage === 'before-refresh' ? 0 : 1);
      assert.equal((await localRecord(page, a)).state.waterEntries[0].amountMl, 350, 'Cancelled A changes remain available in A\'s local diary');
    }, {
      rpc: async ({route, entry}) => {
        if (entry.id === a && entry.path.endsWith('/save_diary') && !intercepted) {
          intercepted = true; heldSave.resolve(); await finishSave.promise;
          await route.fulfill({status: 401, json: {code: 'PGRST301'}}); return true;
        }
        return false;
      },
      auth: async ({route, request, url}) => {
        if (url.pathname === '/auth/v1/token' && request.postDataJSON()?.refresh_token === mockSession(a).refresh_token) {
          refreshRequests++; heldRefresh.resolve(); await finishRefresh.promise;
          await route.fulfill({json: {...mockSession(a), expires_in: 3600}}); return true;
        }
        return false;
      },
    });
  });
}

